// Which image this is, as compile-time constants in every image: the assembly
// name, the build id (build.ps1 and run_build.ps1 pass /p:BuildId=sha[+dirty]
// [-tag]) and, in the kernel, which CoreCLR fork build is linked.
//
// Referenced from std-no-runtime/Generators.props, so it runs for the kernel
// and for every app (not for CoreLib, which is not an image). An image that
// does not see SharpOS.Generated.ImageInfo did not run the image's generators
// at all.
//
// An app also hands its name and id to CoreLib (AppRuntime.SetBuildInfo) from
// a module initializer: CoreLib serves every app and prints the banner and the
// error reports with them. The MSBuild properties come in through
// CompilerVisibleProperty (Generators.props): BuildId, SharpOsImageKind
// (Kernel/App), SharpOsForkConfig.

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace ImageInfo.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class ImageInfoGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var input = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "")
            .Combine(context.AnalyzerConfigOptionsProvider.Select(static (o, _) =>
                (Property(o, "BuildId"), Property(o, "SharpOsImageKind"), Property(o, "SharpOsForkConfig"))));

        context.RegisterSourceOutput(input, static (ctx, pair) =>
        {
            string name = pair.Left;
            (string buildId, string kind, string fork) = pair.Right;

            // CoreLib is not an image: the program built over it is, and it
            // sees CoreLib's internals — a second ImageInfo there would only
            // shadow the program's own (CS0436).
            if (name == "System.Private.CoreLib")
                return;

            var source = new StringBuilder();
            source.Append("// <auto-generated/> by ImageInfo.Generator.ImageInfoGenerator\n");
            source.Append("namespace SharpOS.Generated\n{\n");
            source.Append("    internal static class ImageInfo\n    {\n");
            source.Append("        public const string AssemblyName = ").Append(Literal(name)).Append(";\n");
            source.Append("        public const string BuildId = ").Append(Literal(buildId.Length == 0 ? "local" : buildId)).Append(";\n");
            source.Append("        public const string ForkConfig = ").Append(Literal(fork.Length == 0 ? "none" : fork)).Append(";\n");
            if (kind == "App")
            {
                source.Append("\n        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
                source.Append("        internal static void Register() => global::SharpOS.AppSdk.AppRuntime.SetBuildInfo(AssemblyName, BuildId);\n");
            }
            source.Append("    }\n}\n");
            ctx.AddSource("ImageInfo.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }

    private static string Property(AnalyzerConfigOptionsProvider options, string name)
        => options.GlobalOptions.TryGetValue("build_property." + name, out string? value) ? value ?? "" : "";

    private static string Literal(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
